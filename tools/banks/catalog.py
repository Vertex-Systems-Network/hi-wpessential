"""Group the elements bank into element types and show, per type, who has it and the richest one.

    python3 tools/banks/catalog.py      ->  banks/catalog.json and banks/CATALOG.md

The richest element of a type (most controls / attributes) is the bar our kit element must beat.
"""
import glob
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
BANK = os.path.join(ROOT, 'banks')

# Element type -> words that identify it in a widget/block name or title (first match wins).
TYPES = [  # specific types first; words match whole name tokens
    ('Products / WooCommerce', ['product', 'products', 'woo', 'woocommerce', 'cart', 'checkout', 'wc']), ('Pricing table', ['pricing', 'price-table']),
    ('Price list / menu', ['price-list', 'price-menu', 'food-menu', 'restaurant-menu']), ('Forms', ['form', 'forms', 'contact', 'newsletter', 'mailchimp', 'cf7', 'wpforms', 'login', 'register', 'gf', 'styler']),
    ('Posts grid / blog', ['post', 'posts', 'blog', 'news', 'archive', 'query', 'loop', 'betterdocs', 'docs']), ('Accordion / FAQ', ['accordion', 'faq', 'toggle']),
    ('Tabs', ['tab', 'tabs']), ('Table', ['table', 'data-table']), ('Testimonial', ['testimonial', 'testimonials', 'review', 'reviews']),
    ('Team member', ['team', 'member', 'profile']), ('Counter / number', ['counter', 'number', 'fun-fact', 'funfact', 'stats']),
    ('Progress bar', ['progress', 'skill', 'skills']), ('Countdown', ['countdown', 'timer']), ('Call to action', ['call-to-action', 'cta', 'promo', 'banner']),
    ('Flip / hover box', ['flip', 'hover-box', 'ihover']), ('Info / icon box', ['icon-box', 'info-box', 'infobox', 'feature', 'features', 'service', 'services']),
    ('Image comparison', ['comparison', 'before-after', 'twentytwenty']), ('Image carousel / slider', ['carousel', 'slider', 'swiper', 'slides']),
    ('Gallery', ['gallery', 'masonry', 'portfolio', 'filterable']), ('Image', ['image', 'picture', 'lottie']),
    ('Video / audio', ['video', 'audio', 'youtube', 'embed']), ('Heading', ['heading', 'title', 'dual-color', 'animated-text', 'fancy', 'text-path']),
    ('Text / rich text', ['text-editor', 'paragraph', 'text', 'drop-cap', 'blockquote', 'quote']), ('Button', ['button', 'buttons', 'creative-button', 'dual-button']),
    ('Icon / icon list', ['icon-list', 'list', 'icon', 'icons']), ('Social', ['social', 'share']), ('Map', ['map', 'maps']),
    ('Timeline / steps', ['timeline', 'step', 'steps', 'process']), ('Menu / navigation', ['menu', 'nav', 'navigation', 'breadcrumb', 'breadcrumbs']),
    ('Search', ['search']), ('Site logo / title', ['logo', 'site-title', 'site-tagline']), ('Modal / popup', ['modal', 'popup', 'lightbox', 'offcanvas', 'off-canvas']),
    ('Divider / spacer', ['divider', 'separator', 'spacer']), ('Alert / notice', ['alert', 'notice', 'notification']), ('Rating', ['rating', 'star']),
    ('Layout: container / row / column', ['container', 'section', 'column', 'columns', 'row', 'group', 'grid', 'stack', 'cover']),
    ('Business hours', ['business-hours', 'opening']), ('Calendar / events', ['calendar', 'event', 'events']),
]


def type_of(item):
    hay = (item['name'].split('/')[-1] + ' ' + item.get('title', '')).lower()
    tokens = set(re.split(r'[^a-z0-9]+', hay))
    joined = '-'.join(re.split(r'[^a-z0-9]+', hay))
    for label, words in TYPES:
        if any((w in tokens) if '-' not in w else (w in joined) for w in words):
            return label
    return 'Other'


def size(item):
    c = item.get('counts', {})
    return c.get('controls', 0) + c.get('attributes', 0) + c.get('supports', 0)


def main():
    types = {}
    for f in sorted(glob.glob(os.path.join(BANK, 'elements', '*', '*.json'))):
        item = json.load(open(f))
        ref = os.path.relpath(f, os.path.join(BANK, 'elements'))[:-5]
        types.setdefault(type_of(item), []).append({'ref': ref, 'title': item.get('title', ''), 'source': item['source_label'],
                                                    'builder': 'Elementor' if item['kind'] == 'elementor-widget' else 'Gutenberg', 'size': size(item),
                                                    'responsive': item.get('counts', {}).get('responsive', 0)})
    out = {}
    for t, items in sorted(types.items(), key=lambda kv: -len(kv[1])):
        items.sort(key=lambda x: -x['size'])
        best = {b: next((x for x in items if x['builder'] == b), None) for b in ('Elementor', 'Gutenberg')}
        out[t] = {'count': len(items), 'sources': sorted({x['source'] for x in items}), 'richest': best, 'items': items}
    json.dump(out, open(os.path.join(BANK, 'catalog.json'), 'w'), indent=1, ensure_ascii=False)
    lines = ['# Elements catalog', '', 'Generated by `tools/banks/catalog.py` from `banks/elements/` (see `banks/README.md`). '
             'For each element type: how many plugins offer it and the richest version per builder — the bar our kit element must beat.', '',
             '| Element type | Elements | Richest in Elementor (options) | Richest in Gutenberg (options) |', '| --- | --- | --- | --- |']
    for t, v in out.items():
        cell = lambda b: '%s — %s (%d)' % (v['richest'][b]['title'], v['richest'][b]['source'], v['richest'][b]['size']) if v['richest'][b] else '—'
        lines.append('| %s | %d | %s | %s |' % (t, v['count'], cell('Elementor'), cell('Gutenberg')))
    open(os.path.join(BANK, 'CATALOG.md'), 'w').write('\n'.join(lines) + '\n')
    # Options bank summary: each option kind and how many elements offer it.
    opts = json.load(open(os.path.join(BANK, 'options', 'index.json')))
    total = len(glob.glob(os.path.join(BANK, 'elements', '*', '*.json')))
    rows = ['# Options bank', '', 'Generated by `tools/banks/catalog.py` from `banks/options/index.json`: every option kind found in %d elements, '
            'and how many elements offer it. `control:` = Elementor control type, `group:` = Elementor group control, `feature:` = derived '
            '(responsive, hover), `supports:` = Gutenberg block supports, `attribute-type:` = Gutenberg attribute types.' % total, '',
            '| Option | Elements | Share |', '| --- | --- | --- |']
    rows += ['| `%s` | %d | %d%% |' % (k, len(v), round(100 * len(v) / max(total, 1))) for k, v in opts.items()]
    open(os.path.join(BANK, 'OPTIONS.md'), 'w').write('\n'.join(rows) + '\n')
    print(len(out), 'types,', len(opts), 'option kinds')


if __name__ == '__main__':
    main()
